// Bundles the surface worker and the model modules it imports into one classic (non-module) script,
// app/src/worker.bundle.js. The app loads that file with fetch() and starts the worker from a Blob URL, which
// works when the page runs in an opaque origin (sandboxed preview iframe) where cross-origin module workers
// are refused. Run after editing any file under app/src/models or app/src/worker.js.
import fs from "node:fs/promises";
const root = new URL("../app/src/", import.meta.url);
const order = ["models/pitchcontrol.js", "models/xt.js", "models/options.js", "worker.js"];
let out = "// GENERATED by pipeline/build_worker.mjs from " + order.join(", ") + " — do not edit.\n\"use strict\";\n";
for (const f of order) {
  let src = await fs.readFile(new URL(f, root), "utf8");
  src = src.replace(/^import[^\n]*\n/gm, "").replace(/^export\s+(const|function|class|let)\s/gm, "$1 ");
  out += `\n// ---- ${f}\n${src}`;
}
await fs.writeFile(new URL("worker.bundle.js", root), out);
console.log("worker.bundle.js", out.length, "bytes");
